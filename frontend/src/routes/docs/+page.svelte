	<h1>Справка</h1>

	<h2>Доступ к платформе</h2>
	<p>
		Учётка создаётся через <a href="/account/register">регистрацию</a> и
		становится рабочей только после одобрения администратором платформы —
		это сделано намеренно, чтобы доступ был только у преподавателей
		колледжа. Если после регистрации не получается войти — учётка ещё
		ждёт одобрения, обратитесь к администратору.
	</p>

	<h2>Создание квиза</h2>
	<p>Два способа, оба на странице <a href="/import">«Импорт»</a> и в <a href="/dashboard">«Мои квизы»</a>:</p>
	<ul>
		<li>
			<b>Вручную</b> — кнопка «Создать» на странице «Мои квизы» открывает
			редактор вопросов.
		</li>
		<li>
			<b>Импорт из GIFT</b> — тот же формат, что уже используется в тестах
			курсов (kst-test). Загружаете файл на странице «Импорт» — вопросы с
			одним верным ответом, с несколькими верными ответами и на
			расстановку по порядку переносятся автоматически. Вопросы на
			соответствие (сопоставить разные понятия) в редакторе не
			поддерживаются — они попадут в отчёт после импорта, такие придётся
			добавить вручную.
		</li>
	</ul>

	<h2>Группы студентов</h2>
	<p>
		На странице <a href="/dashboard/groups">«Группы»</a> создаётся список
		группы — ФИО можно вставить одним куском текста, по одному имени на
		строку, прямо из ведомости. При запуске игры группу можно выбрать —
		тогда студент на входе выбирает своё имя из списка вместо ввода
		произвольного ника, а посторонний зайти не сможет.
	</p>

	<h2>Проведение игры</h2>
	<p>
		Кнопка «Начать игру» на карточке квиза открывает экран ведущего с
		PIN-кодом и QR — студенты подключаются с телефона на странице
		<a href="/play">«Играть»</a>. Вы управляете темпом вручную: показываете
		следующий вопрос, останавливаете время, открываете результаты.
	</p>

	<h2>Управление учётками (для администратора)</h2>
	<p>
		Одобрение заявок на регистрацию, создание учёток напрямую, сброс
		пароля и удаление — на странице <a href="/account/admin">«Управление
		учётками»</a>. Доступна только тем, кого администратор платформы явно
		внёс в список допуска.
	</p>
