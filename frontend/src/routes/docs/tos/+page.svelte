	<h1>Условия использования</h1>

	<h2>Что это за платформа</h2>
	<p>
		КСТ.Квиз — платформа для живых квизов и опросов на занятиях ГБПОУ
		«Колледж современных технологий имени Героя Советского Союза
		М.Ф. Панова». Доступ — только преподавателям и студентам колледжа,
		учётка преподавателя становится рабочей после одобрения
		администратором платформы.

	</p>

	<h2>Что нельзя размещать</h2>
	<p>
		Только учебные материалы. Нельзя размещать материалы, нарушающие
		законодательство Российской Федерации, а также содержание, не имеющее
		отношения к учебному процессу. Администратор платформы вправе удалить
		такой материал.
	</p>

	<h2>Права администратора платформы</h2>
	<p>
		Администратор может одобрять и удалять учётные записи, управлять
		доступом и при необходимости удалять материалы, нарушающие эти условия.
		Данные пользователей не передаются третьим лицам и не публикуются —
		подробнее в <a href="/docs/privacy-policy">политике обработки
		персональных данных</a>.
	</p>

	<h2>Права пользователя</h2>
	<p>
		Вы можете запросить удаление своей учётной записи и связанных с ней
		данных, обратившись к администратору платформы.
	</p>
